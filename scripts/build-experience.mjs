import {writeBuyerPacks} from './build-buyer-packs.mjs';
import {writeOwnedProof} from './build-owned-proof.mjs';
import {priceList} from '../src/shared.mjs';
import {civicAssetState,copyCivicAssets} from './build-civic-assets.mjs';
import {readFile,writeFile,mkdir,cp,rm,stat} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {renderPages} from '../src/pages.mjs';
const root=resolve(import.meta.dirname,'..');
const json=async name=>JSON.parse(await readFile(resolve(root,name),'utf8'));
const [config,offers,map,tokens,geography]=await Promise.all(['config/site.json','config/offers.json','authority/v5/site-map.json','authority/v5/design-tokens.json','authority/v5/geography.json'].map(json));
Object.assign(config,await civicAssetState(root,config));
const output=resolve(root,'.runtime/experience-review');
if(output!==resolve(root,'.runtime/experience-review'))throw Error('Invalid experience output');
await rm(output,{recursive:true,force:true});await mkdir(output,{recursive:true});
await cp(resolve(root,'src/assets'),resolve(output,'assets'),{recursive:true});
await cp(resolve(root,'src/assets/brand/favicon.ico'),resolve(output,'favicon.ico'));
await cp(resolve(root,'src/client.js'),resolve(output,'assets/client.js'));
await cp(resolve(root,'src/shared.mjs'),resolve(output,'assets/shared.mjs'));
await copyCivicAssets(root,output,config);
const prices=priceList(offers);
await writeFile(resolve(output,'assets/prices.json'),JSON.stringify(prices));
await writeBuyerPacks(output,offers);
await writeOwnedProof(root,output,offers);
const preview={...config,mode:'staging',formMode:'synthetic',reviewOnly:false,searchIndexing:false};
const pages=renderPages({config:preview,offers,map,tokens,geography});
for(const page of pages){const file=resolve(output,`.${page.path}index.html`);await mkdir(dirname(file),{recursive:true});await writeFile(file,page.html);}
await writeFile(resolve(output,'robots.txt'),'User-agent: *\nDisallow: /\n');
await stat(resolve(output,'assets/editions/buffalo-dusk/motion-1280.mp4'));
console.log(`Experience preview built: ${pages.length} routes; synthetic inquiry; ${output}`);
