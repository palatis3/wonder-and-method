// Rebuild only when the cited Census estimate file or directory changes.
// Usage: node scripts/prepare-county-city-populations.mjs <SUB-EST2025.csv>
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {serviceStates,countySearchText} from '../src/service-area-directory.mjs';
import {normalizeCountyQuery} from '../src/assets/county-directory.js';

const input=process.argv[2];
if(!input)throw Error('Pass the locally retained Census SUB-EST2025 CSV.');
const raw=await readFile(input),text=new TextDecoder('windows-1252').decode(raw);
const lines=text.trim().split(/\r?\n/),headers=lines.shift().split(',');
// Source fields can be quoted, including comma-bearing names.
const parse=line=>[...line.matchAll(/(?:^|,)(?:"((?:[^"]|"")*)"|([^,]*))/g)].map(match=>(match[1]??match[2]).replaceAll('""','"'));
const states=new Map(serviceStates.map(state=>[state.name==='Washington, DC'?'District of Columbia':state.name,state.id]));
const populations=new Map(),ambiguous=new Set();
for(const line of lines){
 const row=Object.fromEntries(parse(line).map((value,index)=>[headers[index],value]));
 if(row.SUMLEV!=='162'||!row.NAME.endsWith(' city')||!states.has(row.STNAME))continue;
 const key=states.get(row.STNAME)+'/'+normalizeCountyQuery(row.NAME.slice(0,-5));
 if(populations.has(key))ambiguous.add(key);
 const value=Number(row.POPESTIMATE2025);
 if(Number.isSafeInteger(value)&&value>=0)populations.set(key,value);
}
for(const key of ambiguous)populations.delete(key);
const names=new Map();
for(const state of serviceStates)for(const county of state.counties){
 const terms=countySearchText(county,state,state.regions.find(region=>region.slugs.includes(county.slug))).split('|');
 for(const term of terms){
  const [type,name]=term.split(':');if(!type.includes('c')&&!type.includes('i'))continue;
  if(!names.has(name))names.set(name,new Set());names.get(name).add(state.id);
 }
}
const output=Object.fromEntries([...names].filter(([,states])=>states.size>1).flatMap(([name,states])=>[...states].filter(state=>populations.has(state+'/'+name)).map(state=>[state+'/'+name,populations.get(state+'/'+name)])).sort(([a],[b])=>a.localeCompare(b,'en')));
const sha256=createHash('sha256').update(raw).digest('hex');
const source='https://www2.census.gov/programs-surveys/popest/datasets/2020-2025/cities/totals/sub-est2025.csv';
await writeFile(new URL('../src/assets/county-city-populations.js',import.meta.url),`// Generated by scripts/prepare-county-city-populations.mjs.\n// ${source}\n// SHA256 ${sha256}\n// Whole-place July 2025 estimates only break ties between equally exact city names.\n// They do not describe county portions, service demand or current availability.\nexport const countyCityPopulations=${JSON.stringify(output)};\n`);
console.log(JSON.stringify({source,sha256,rows:output&&Object.keys(output).length,bytes:Buffer.byteLength(JSON.stringify(output)),ambiguousKeysExcluded:[...ambiguous]}));
