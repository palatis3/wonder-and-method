import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,access} from 'node:fs/promises';
import {draftScope} from '../scripts/create-job.mjs';
import {buyerPacks} from '../src/buyer-packs.mjs';
import {renderPages} from '../src/pages.mjs';
import {assertPackageVisualOffers} from '../src/package-visuals.mjs';
const read=async path=>JSON.parse(await readFile(new URL('../'+path,import.meta.url),'utf8'));
const [offers,config,map,geography]=await Promise.all(['config/offers.json','config/site.json','authority/v5/site-map.json','authority/v5/geography.json'].map(read));
const tiers=[['launch_site',2950,8,0],['focused_site',4500,10,0],['business_site',7500,15,1],['signature_site',11500,20,2]];
const approved=await read('operations/v3-offers-20261029/approved-plan-catalog.json');

test('approved V3 website limits survive accepted snapshots and buyer packs',async()=>{
 const packs=buyerPacks(offers);
 for(const[id,price,pages,articles]of tiers){
  const p=offers[id],draft=await draftScope(id,'synthetic-expanded-packages'),source=approved.plans.find(plan=>plan.id===p.v3_plan_id);
  assert.equal(p.public_price,price);assert.equal(source.price,price);assert.equal(p.marketing_page_cap,pages);assert.equal(p.launch_content.articles,articles);
  assert.deepEqual(p.payment_schedule.map(m=>m.percent),[40,30,30]);assert.deepEqual(p.payment_schedule.map(m=>m.amount),[price*.4,price*.3,price*.3]);
  const expectedIncludes=source.includes.map(line=>id==='business_site'?line.replace('One can be a researched practical guide answering one agreed buyer question;', 'The allowance includes up to one researched practical guide, each answering one agreed buyer question;').replace('Both count inside the 15-page total.', 'These count inside the 15-page total.'):line);
  assert.deepEqual(draft.commercial_boundaries.deliverables,expectedIncludes);assert.deepEqual(draft.exclusions,source.excludes);
  for(const check of source.acceptance)assert.ok(draft.acceptance_tests.includes(check));
  assert.equal(draft.commercial_snapshot.version,offers.version);
  const pack=packs.find(pack=>pack.id===id),text=JSON.stringify(pack.sections);
  for(const phrase of ['policy','recorded demonstration','word','Search-ready page planning'])assert.ok(text.includes(phrase),id+' '+phrase);
  assert.match(text,/three client|three .*policy/i);assert.match(text,/outside|separately from/);
  assert.equal(pack.price,price);assert.deepEqual(draft.commercial_snapshot.offer.v3.includes,expectedIncludes);
 }
 assert.equal(offers.storefront.public_price,8500);assert.match(offers.storefront.v3.includes.join(' '),/six marketing\/information pages/);
});

test('V3 public metadata states the approved website page ladder and retires stale posters',async()=>{
 const pages=renderPages({config,offers,map,geography});
 for(const path of ['/pricing/','/services/web-design/']){
  const html=pages.find(p=>p.path===path).html,description=html.match(/<meta name="description" content="([^"]+)"/)?.[1];
  assert.match(description,/four website|8, 10, 15(?:,| or| and) 20/);for(const cap of [8,10,15,20])assert.match(html,new RegExp('Up to '+cap+' pages'));assert.doesNotMatch(html,/assets\/package-visuals/);
 }
 await assert.rejects(access(new URL('../src/assets/creative-samples/promotion-template.svg',import.meta.url)));
 assert.throws(()=>assertPackageVisualOffers(offers),/Regenerate package comparison/);
});
