import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,access} from 'node:fs/promises';
import {draftScope} from '../scripts/create-job.mjs';
import {buyerPacks} from '../src/buyer-packs.mjs';
import {renderPages} from '../src/pages.mjs';
import {assertPackageVisualOffers} from '../src/package-visuals.mjs';
const read=async path=>JSON.parse(await readFile(new URL('../'+path,import.meta.url),'utf8'));
const [offers,config,map,geography]=await Promise.all(['config/offers.json','config/site.json','authority/v5/site-map.json','authority/v5/geography.json'].map(read));
const tiers=[['launch_site',1400,6,0,2,1,0,0],['focused_site',2350,15,2,3,3,3,6],['signature_site',3700,30,4,5,6,6,12]];

test('expanded scope survives both the accepted-offer snapshot and generated buyer pack',async()=>{
 const packs=buyerPacks(offers);
 for(const[id,price,pages,articles,competitors,launch,promo,photos]of tiers){
  const p=offers[id],draft=await draftScope(id,'synthetic-expanded-packages');
  assert.equal(p.public_price,price);assert.equal(p.marketing_page_cap,pages);
  assert.equal(p.launch_content.articles,articles);assert.equal(p.launch_content.within_marketing_page_cap,true);
  assert.equal(p.search_research.competitor_limit,competitors);
  assert.deepEqual(p.graphic_counts,{launch,promotional:promo,total:launch+promo,supplied_photo_edits:photos});
  assert.equal(p.search_followup.articles,0);assert.equal(p.search_followup.duration_days,0);
  for(const key of ['launch_content','search_research','graphic_counts','promotional_graphics'])assert.deepEqual(draft.commercial_boundaries[key],p[key],id+' '+key);
  assert.equal(draft.commercial_snapshot.version,offers.version);
  const pack=JSON.stringify(packs.find(pack=>pack.id===id));
  for(const text of [p.page_scope,p.seo_foundation,p.launch_content.summary,p.search_research.next_steps])assert.ok(pack.includes(text),id+' missing '+text.slice(0,50));
  assert.equal(offers.decision_pack_examples[id].pages.length,pages);
 }
 assert.match(offers.signature_site.search_research.next_steps,/90-day sequence/);
 assert.match(offers.signature_site.search_research.next_steps,/delivery and monitoring after launch are separately agreed/);
 assert.equal(offers.audit_sprint.page_cap,12);
 assert.deepEqual(Object.values(offers.plans).map(p=>p.monthly_price),[150,400,800]);
});

